/* Read-only checks; synthetic edge cases replace this browser's response only. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/rovic/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict'), fs = require('node:fs');
const origin = process.env.QA_URL || 'http://127.0.0.1:8013';
const output = 'docs/public-announcement-inline-2026-11-09';
(async () => {
    const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_EXECUTABLE || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
    try {
        fs.mkdirSync(output, { recursive: true });
        const page = await browser.newPage(), errors = [], checks = [];
        page.on('pageerror', error => errors.push(error.message));
        const dialog = page.locator('[data-public-dialog]');
        const open = async () => {
            await page.locator('.notice-row-action').first().click();
            await page.waitForSelector('.announcement-poster-dialog .announcement-poster');
            await dialog.locator('img').evaluateAll(images => Promise.all(images.map(img => img.decode().catch(() => {}))));
        };
        for (const theme of ['light', 'dark']) for (const width of [1440, 768, 390, 320]) {
            await page.setViewportSize({ width, height: 900 });
            await page.goto(origin + '/announcements/?category=announcements');
            await page.evaluate(theme => document.documentElement.dataset.publicTheme = theme, theme);
            const url = page.url();
            await open();
            assert.equal(page.url(), url);
            const box = await dialog.boundingBox();
            assert(box.x >= 0 && box.x + box.width <= width && box.y >= 0 && box.y + box.height <= 900);
            assert(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
            assert.equal(await dialog.locator('.announcement-poster-action').count(), 0);
            assert.equal(await dialog.getByText('Explore More', { exact: false }).count(), 0);
            assert.equal(await dialog.locator('.announcement-poster-copy h3').evaluate(el => getComputedStyle(el).color), theme === 'dark' ? 'rgb(244, 242, 236)' : 'rgb(28, 26, 24)');
            assert.equal(await dialog.locator('.announcement-poster-summary').evaluate(el => getComputedStyle(el).color), theme === 'dark' ? 'rgb(197, 192, 184)' : 'rgb(107, 102, 95)');
            assert.equal(await dialog.evaluate(el => getComputedStyle(el).backgroundColor), theme === 'dark' ? 'rgb(36, 34, 32)' : 'rgb(244, 242, 236)');
            await page.keyboard.press('Tab');
            assert(await dialog.locator('[aria-label="Close details"]').evaluate(el => el === document.activeElement));
            await page.keyboard.press('Shift+Tab');
            assert(await dialog.locator('[aria-label="Close details"]').evaluate(el => el === document.activeElement));
            const copyWidth = await dialog.locator('.announcement-poster-copy').evaluate(el => el.getBoundingClientRect().width);
            const rowWidth = await dialog.locator('.announcement-poster-bottom').evaluate(el => el.getBoundingClientRect().width);
            assert(Math.abs(copyWidth - rowWidth) <= 1);
            await page.screenshot({ path: `${output}/${theme}-${width}.png` });
            if (width === 1440) await dialog.screenshot({ path: `${output}/card-${theme}.png` });
            await page.keyboard.press('Escape');
            assert(await page.locator('.notice-row-action').first().evaluate(el => el === document.activeElement));
            checks.push({ theme, width, cardWidth: box.width, cardHeight: box.height });
        }
        await open();
        await page.evaluate(() => document.documentElement.dataset.contrast = 'true');
        assert.equal(await dialog.locator('.announcement-poster-copy h3').evaluate(el => getComputedStyle(el).color), 'rgb(17, 17, 17)');
        await page.screenshot({ path: `${output}/contrast-320.png` });
        await page.evaluate(() => delete document.documentElement.dataset.contrast);
        await page.emulateMedia({ forcedColors: 'active' });
        assert.equal(await dialog.locator('.announcement-poster-action').count(), 0);
            assert.equal(await dialog.getByText('Explore More', { exact: false }).count(), 0);
        await page.emulateMedia({ forcedColors: 'none' });
        await page.keyboard.press('Escape');
        const href = await page.locator('.notice-row-action').first().getAttribute('href');
        const fragment = await (await page.request.get(origin + href + '?popup=1')).text();
        const inject = html => page.route('**/announcements/*/?popup=1', route => route.fulfill({ status: 200, contentType: 'text/html', body: html }));
        await inject(fragment.replace(/(<h3[^>]*>)[\s\S]*?(<\/h3>)/, '$1A long announcement title that remains completely readable$2')
            .replace('<span class="announcement-poster-summary" translate="no">', '<span class="announcement-poster-summary" translate="no">' + 'Additional published information. '.repeat(50)));
        await open();
        await page.evaluate(() => document.documentElement.style.fontSize = '200%');
        assert(await dialog.evaluate(el => el.scrollHeight > el.clientHeight && el.scrollWidth <= el.clientWidth + 1));
        await dialog.evaluate(el => el.scrollTop = el.scrollHeight);
        assert(await dialog.locator('[aria-label="Close details"]').isVisible());
        await page.screenshot({ path: `${output}/large-text-320.png` });
        await page.keyboard.press('Escape');
        await page.evaluate(() => document.documentElement.style.fontSize = '');
        await page.unroute('**/announcements/*/?popup=1');
        const noImage = fragment.replace(/<img[^>]*data-announcement-poster-image[^>]*>/g, '');
        await inject(noImage);
        await open();
        await page.screenshot({ path: `${output}/no-image-320.png` });
        await page.keyboard.press('Escape');
        await page.unroute('**/announcements/*/?popup=1');
        await inject(noImage.replace('<div class="announcement-poster-artwork">', '<div class="announcement-poster-artwork"><img src="/missing-announcement.png" alt="Synthetic image check" data-announcement-poster-image>'));
        await page.route('**/missing-announcement.png', route => route.abort());
        await open();
        await page.waitForFunction(() => document.querySelector('[data-announcement-poster-image]').hidden);
        await dialog.locator('[aria-label="Close details"]').click();
        assert.equal(await page.locator('dialog[open]').count(), 0);
        await page.unroute('**/announcements/*/?popup=1');
        await page.route('**/announcements/*/?popup=1', route => route.fulfill({ status: 404 }));
        await page.locator('.notice-row-action').first().click();
        await dialog.getByText('These details could not be loaded.', { exact: false }).waitFor();
        assert(!await dialog.evaluate(el => el.classList.contains('announcement-poster-dialog')));
        await page.keyboard.press('Escape');
        await page.unroute('**/announcements/*/?popup=1');
        await page.setViewportSize({ width: 1440, height: 900 });
        await open();
        await page.mouse.click(5, 5);
        assert.equal(await page.locator('dialog[open]').count(), 0);
        const plain = await browser.newPage({ javaScriptEnabled: false });
        await plain.goto(origin + '/announcements/?category=announcements');
        await plain.locator('.notice-row-action').first().click();
        assert(await plain.getByRole('heading', { name: 'Announcement details' }).isVisible());
        await plain.close();
        assert.deepEqual(errors, []);
        fs.writeFileSync(`${output}/results.json`, JSON.stringify({ checks, keyboard: true, contrast: true, longText: true, imageFallback: true, noFullPageAction: true, errorRecovery: true, noJavaScript: true, errors }, null, 2));
        console.log('Announcement banner passed: eight theme/viewport checks, keyboard, contrast, long text, image fallback, popup-only reading and error recovery.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
